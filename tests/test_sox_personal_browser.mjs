import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir, mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';

const require = createRequire(import.meta.url);
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.argv[2] || 'http://127.0.0.1:8787';
assert.ok(['127.0.0.1','localhost','[::1]'].includes(new URL(base).hostname),'Use the local Worker.');
const output=process.env.SOX_SCREENSHOT_DIR || await mkdtemp(join(tmpdir(),'funding-sox-personal-'));
await mkdir(output,{recursive:true});
const actual=await (await fetch(base+'/api/sox')).json();
const live=actual.live;
assert.equal(actual.status.state,'READY');
assert.equal(live.public_use_confirmed,false);
assert.equal(live.personal_use_confirmed,true);
assert.equal(live.analysis_use,'personal_noncommercial');
assert.equal(live.sources.sox.status,'ok');
assert.ok(live.stats.drawdown.n>0 && live.stats.rebound.n>0,'Real collected prices must produce both series.');
assert.equal(live.points.drawdown.length,live.stats.drawdown.n);
assert.equal(live.points.rebound.length,live.stats.rebound.n);
assert.ok(!JSON.stringify(live).includes('sox_close'),'Raw closes must remain private.');

const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1400},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto(base+'/#sox-research',{waitUntil:'domcontentloaded'});
  const host=page.locator('#sox-research');
  await page.waitForFunction(()=>document.querySelector('#sox-research [data-sx="badge"]').textContent==='일별 갱신');
  assert.equal(await host.locator('[data-mode="live"]').getAttribute('aria-selected'),'true');
  const count=live.points.drawdown.length+live.points.rebound.length;
  assert.equal(await host.locator('[data-tip]').count(),count);
  assert.equal(await host.locator('[data-sx="stat-blue"]').innerText(),`r=${live.stats.drawdown.r.toFixed(3)}, n=${live.stats.drawdown.n}`);
  assert.equal(await host.locator('[data-sx="stat-orange"]').innerText(),`r=${live.stats.rebound.r.toFixed(3)}, n=${live.stats.rebound.n}`);
  const freshness=await host.locator('[data-sx="freshness"]').innerText();
  assert.ok(freshness.includes(`SOX 종가 기준: ${live.sources.sox.observed_through}`));
  assert.ok(freshness.includes(`최근 TGA·순발행 입력: ${live.latest_macro.date}`));
  assert.ok(!freshness.includes('이용 확인 대기'));
  assert.match(await host.locator('[data-sx="sample"]').innerText(),/개인·비상업 연구용/);
  await host.locator('details').first().locator('summary').click();
  assert.match(await host.locator('[data-sx="methods"]').innerText(),/Copyright © 2025, Nasdaq, Inc/);
  await host.locator('details').first().locator('summary').click();
  assert.ok(!(await host.locator('[data-sx="recent"]').innerText()).includes('이용 확인 대기'));
  await host.screenshot({path:join(output,'sox-personal-desktop.png')});
  await host.locator('[data-mode="reference"]').click();
  assert.equal(await host.locator('[data-tip]').count(),14);
  assert.equal(await host.locator('[data-sx="stat-blue"]').innerText(),'r=0.961, n=6');
  assert.equal(await host.locator('[data-sx="stat-orange"]').innerText(),'r=0.915, n=8');
  await host.locator('[data-mode="live"]').click();
  assert.equal(await host.locator('[data-tip]').count(),count);
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(200);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
  assert.equal(await host.locator('[data-sx="stat-blue"]').isVisible(),true);
  assert.equal(await host.locator('[data-sx="stat-orange"]').isVisible(),true);
  await host.screenshot({path:join(output,'sox-personal-mobile.png')});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({result:'passed',scope:'Actual local SOX collection, no intercepted responses',drawdown:live.stats.drawdown.n,rebound:live.stats.rebound.n,latest_sox:live.sources.sox.observed_through,screenshots:output}));
} finally { await browser.close(); }
